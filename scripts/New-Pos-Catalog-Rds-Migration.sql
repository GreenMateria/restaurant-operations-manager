-- Apply with the schema-capable RDS administrator before deploying new-POS catalog API routes.
BEGIN;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'production_profiles_id_location_key') THEN
        ALTER TABLE production_profiles
            ADD CONSTRAINT production_profiles_id_location_key UNIQUE (id, location_id);
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS new_pos_menu_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id INTEGER NOT NULL REFERENCES locations(id),
    name TEXT NOT NULL,
    name_key TEXT NOT NULL,
    production_profile_id INTEGER,
    active INTEGER NOT NULL DEFAULT 1,
    CONSTRAINT new_pos_menu_items_location_name_key UNIQUE (location_id, name_key),
    CONSTRAINT new_pos_menu_items_profile_location_fk
        FOREIGN KEY (production_profile_id, location_id)
        REFERENCES production_profiles(id, location_id)
);

GRANT SELECT, INSERT, UPDATE ON new_pos_menu_items TO operations_app;
GRANT USAGE, SELECT ON SEQUENCE new_pos_menu_items_id_seq TO operations_app;

UPDATE schema_version SET version = GREATEST(version, 25);
COMMIT;
